"""Export v2 offline fixtures for layout-preview-v2.html.

Run: .venv/Scripts/python tools/town_layout_samples_v2.py

Writes app/static/map-art/town/layout-samples-v2.js only (the legacy
layout-samples.js is left untouched). Items are packed as
[id_index, x, bottom, key] against a shared id table to keep the file small;
the preview page unpacks them before calling TownRender.render.
No world, DB, civ-atlas location or game service is read or modified.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.town_layout import FACILITY_DISTRICTS, layout, load_catalog, site_layout  # noqa: E402

COMBOS = [('west', r) for r in ('common', 'elf', 'dwarf', 'orc')] + [('east', 'common'),
                                                                     ('arab', 'common')]
SHAPES = ('irregular', 'square')
SEEDS = (1, 7)
SAMPLES = [
    ('village', '村落', 'village', 'village', 'well_field',
     ['well', 'inn', 'temple', 'mill', 'granary']),
    ('town', '城镇', 'town', 'market_town', 'well_field',
     ['town_hall', 'market_hall', 'forge', 'inn', 'granary', 'stable', 'infirmary',
      'cemetery', 'temple']),
    ('city', '城市', 'city', 'city', 'river',
     ['city_wall', 'gate', 'town_hall', 'lord_hall', 'market_hall', 'temple', 'academy',
      'barracks', 'warehouse', 'smelter', 'tannery', 'kiln', 'cistern', 'forge', 'forge',
      'inn', 'inn', 'granary', 'bridge', 'well', 'well']),
    ('port', '港口', 'town', 'port', 'river',
     ['town_hall', 'market_hall', 'dock', 'dock', 'warehouse', 'warehouse', 'inn', 'well',
      'stable', 'temple']),
    ('fortress', '要塞', 'small_town', 'border_fortress', 'well_field',
     ['city_wall', 'gate', 'lord_hall', 'barracks', 'watchtower', 'forge', 'stable',
      'granary', 'well']),
]
LAYERS = ('underlay', 'ground', 'items')


class Packer:
    def __init__(self):
        self.ids, self.index = [], {}

    def id(self, ident):
        if ident not in self.index:
            self.index[ident] = len(self.ids)
            self.ids.append(ident)
        return self.index[ident]

    def pack(self, plan):
        out = {k: v for k, v in plan.items() if k not in LAYERS}
        out['grid'] = {k: v for k, v in plan['grid'].items() if k not in ('interior', 'yard')}
        for layer in LAYERS:
            rows = []
            for it in plan.get(layer, []):
                key = it['key'] if it['key'] != it['bottom'] else None
                row = [self.id(it['id']), round(it['x'], 2), round(it['bottom'], 2)]
                if key is not None:
                    row.append(round(key, 3))
                rows.append(row)
            out[layer] = rows
        return out


def town(ident, scale, town_type, water, facilities):
    districts = sorted(set(FACILITY_DISTRICTS.get(k, 'residential') for k in facilities)
                       | {'residential'})
    return {'town_id': ident, 'skeleton': {'scale': scale, 'town_type': town_type,
                                           'water': {'source': water}},
            'built': {'districts': [{'id': d, 'kind': d} for d in districts],
                      'facilities': [{'id': f'{k}_{i}', 'kind': k,
                                      'district': FACILITY_DISTRICTS.get(k, 'residential')}
                                     for i, k in enumerate(facilities)]}}


def export():
    catalog = load_catalog()
    packer, towns, sites = Packer(), [], []
    for ident, name, scale, town_type, water, facilities in SAMPLES:
        data = town(ident, scale, town_type, water, facilities)
        for style, race in COMBOS:
            for shape in SHAPES:
                for seed in SEEDS:
                    plan = layout(data, style, race, seed, catalog, wall_shape=shape)
                    towns.append({'sample': ident, 'name': name, 'style': style, 'race': race,
                                  'shape': shape, 'seed': seed, 'layout': packer.pack(plan)})
    seen = set()
    for m in sorted(catalog['meta'], key=lambda m: m['id']):
        if m.get('category') != 'site':
            continue
        key = (m['style'], m['resource'], m.get('subtype'))
        if key in seen:
            continue
        seen.add(key)
        plan = site_layout(m, m['style'], seed=1, catalog=catalog)
        sites.append({'style': m['style'], 'resource': m['resource'], 'subtype': m.get('subtype'),
                      'main': m['id'], 'layout': packer.pack(plan)})
    target = ROOT / 'app/static/map-art/town/layout-samples-v2.js'
    body = json.dumps({'ids': packer.ids, 'towns': towns, 'sites': sites},
                      separators=(',', ':'), ensure_ascii=False)
    target.write_text('/* generated by tools/town_layout_samples_v2.py */\n'
                      'window.TOWN_LAYOUT_SAMPLES_V2 = ' + body + ';\n', encoding='utf-8')
    print(f'Exported {len(towns)} towns + {len(sites)} sites, {len(body) // 1024} KB -> {target}')


if __name__ == '__main__':
    export()
